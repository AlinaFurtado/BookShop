-- Compatible with the existing Hibernate-created Neon tables.
-- IF NOT EXISTS preserves existing tables, identities and reader records.
-- Hibernate validates the mapped columns after Flyway completes.
CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS shelf_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT,
    work_id VARCHAR(100),
    title VARCHAR(500),
    author VARCHAR(500),
    genre VARCHAR(100),
    cover_id INTEGER,
    rating DOUBLE PRECISION,
    rating_count INTEGER,
    publish_year INTEGER,
    description VARCHAR(2000),
    status VARCHAR(20),
    finish_date DATE,
    passport_destination VARCHAR(120),
    passport_mood VARCHAR(80),
    passport_favorite_character VARCHAR(120),
    passport_quote VARCHAR(600),
    passport_memory VARCHAR(2000),
    CONSTRAINT uk_shelf_owner_work UNIQUE (owner_id, work_id)
);

CREATE TABLE IF NOT EXISTS book_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    work_id VARCHAR(100) NOT NULL,
    rating INTEGER NOT NULL,
    review_text VARCHAR(2000) NOT NULL,
    spoiler BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_review_owner_work UNIQUE (owner_id, work_id)
);
